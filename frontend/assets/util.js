export async function copy(text) {
  try {
    await navigator.clipboard.writeText(text);
  } catch {
    const ta = Object.assign(document.createElement('textarea'), { value: text });
    document.body.append(ta);
    ta.select();
    document.execCommand('copy');
    ta.remove();
  }
}

export function toast(message, type = 'ok') {
  let box = $('.toasts');
  if (!box) { box = Object.assign(document.createElement('div'), { className: 'toasts' }); document.body.append(box); }
  const el = document.createElement('div');
  el.className = `toast ${type === 'error' ? 'error' : ''}`;
  el.setAttribute('role', 'status');
  el.innerHTML = `${icon(type === 'error' ? 'alert' : 'check')}<span>${esc(message)}</span>`;
  box.append(el);
  setTimeout(() => { el.classList.add('out'); setTimeout(() => el.remove(), 220); }, 3000);
}

/** Promise-based confirm dialog in the app's style (no browser alert boxes). */
export function confirmDialog({ title, text, ok = 'Confirm', danger = false }) {
  return new Promise((resolve) => {
    const scrim = Object.assign(document.createElement('div'), { className: 'scrim' });
    const modal = document.createElement('div');
    modal.className = 'modal';
    modal.setAttribute('role', 'dialog');
    modal.innerHTML = `<div class="b"><h3>${esc(title)}</h3><p>${esc(text)}</p></div>
      <div class="f"><button class="btn" data-a="no">Cancel</button><button class="btn btn-dark ${danger ? 'danger' : ''}" data-a="yes">${esc(ok)}</button></div>`;
    const close = (v) => { scrim.remove(); modal.remove(); document.removeEventListener('keydown', onKey); resolve(v); };
    const onKey = (e) => e.key === 'Escape' && close(false);
    scrim.onclick = () => close(false);
    modal.onclick = (e) => { const a = e.target.closest('[data-a]')?.dataset.a; if (a) close(a === 'yes'); };
    document.addEventListener('keydown', onKey);
    document.body.append(scrim, modal);
    modal.querySelector('[data-a="yes"]').focus();
  });
}

/** QR code as inline SVG (qrcode-generator, loaded as a global). */
export function qrSvg(text) {
  if (!window.qrcode) return '';
  const qr = window.qrcode(0, 'M');
  qr.addData(text);
  qr.make();
  return qr.createSvgTag({ cellSize: 4, margin: 0, scalable: true });
}

/** Adds .is-visible to [data-reveal] elements as they scroll into view. */
export function reveal(root = document) {
  const items = $$('[data-reveal]', root);
  if (!('IntersectionObserver' in window)) return items.forEach((el) => el.classList.add('is-visible'));
  const io = new IntersectionObserver((entries) => entries.forEach((e) => {
    if (e.isIntersecting) { e.target.classList.add('is-visible'); io.unobserve(e.target); }
  }), { rootMargin: '0px 0px -8% 0px', threshold: 0.12 });
  items.forEach((el) => io.observe(el));
}

